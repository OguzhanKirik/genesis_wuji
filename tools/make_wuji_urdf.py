#!/usr/bin/env python3
"""Vendor the Adam-U + Wuji Hand 2 body from adam-moveit as a standalone URDF.

adam-moveit already carries the design team's Wuji delivery, de-flattened and
with hull collisions (ws/src/adam_u_description/urdf/adam_u_body_genesis_wuji.xacro,
generated by its scripts/vendor_model.py -- see docs/genesis_wuji_design.md
there). This script takes THAT file, not the raw delivery, because the raw
export duplicates every descendant's geometry into its ancestors.

What it changes, and nothing else:

  1. package://adam_u_description/meshes/genesis_wuji/X.obj
       -> ../meshes/visual/X.obj             (plus X.mtl when the OBJ names one)
     package://adam_u_description/meshes/genesis_wuji_collision_hull/X.stl
       -> ../meshes/collision/X.stl
     Relative to the URDF, like assets/robots/adam_u/urdf/adam_u.urdf, so the
     Isaac Lab converter resolves them without a ROS package index.
  2. The two prismatic lifting-column joints become FIXED at q=0 (fully
     extended). Nothing drives the column; adam-moveit's Isaac stage freezes
     them the same way after the torso slid down its own column under gravity.
  3. The xacro fragment becomes a <robot name="adam_u_wuji"> document.

Only the meshes the URDF references are copied (61 OBJ + their MTL, 52 STL),
not the whole 69 MB delivery. The URDF header records the adam-moveit commit
and the sha256 of the source xacro so the vendoring can be audited.

    python3 tools/make_wuji_urdf.py                # defaults below
    python3 tools/make_wuji_urdf.py --check        # verify outputs are current

Host-side, plain Python, no ROS.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import os
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)

DEFAULT_MOVEIT = "/home/revel/adam-moveit"
XACRO_REL = "ws/src/adam_u_description/urdf/adam_u_body_genesis_wuji.xacro"
MESH_REL = "ws/src/adam_u_description/meshes"
OUT_DIR = os.path.join(REPO, "adam_u_isaac_lab", "assets", "robots", "adam_u_wuji")

PKG_VISUAL = "package://adam_u_description/meshes/genesis_wuji/"
PKG_HULL = "package://adam_u_description/meshes/genesis_wuji_collision_hull/"

COLUMN_JOINTS = ("lifting_Columns_middle_joint", "lifting_Columns_top_visual_joint")


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def git_head(repo: str) -> str:
    try:
        out = subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"],
                             check=True, capture_output=True, text=True).stdout.strip()
        dirty = subprocess.run(["git", "-C", repo, "status", "--porcelain", "--", XACRO_REL, MESH_REL],
                               check=True, capture_output=True, text=True).stdout.strip()
        return out + (" (source files modified in working tree)" if dirty else "")
    except Exception as exc:  # noqa: BLE001
        return f"unknown ({exc})"


def mtl_of(obj_path: str) -> str | None:
    with open(obj_path, "r", errors="replace") as f:
        for line in f:
            if line.startswith("mtllib"):
                return line.split(None, 1)[1].strip()
            if line.startswith(("v ", "f ")):
                break
    return None


def build(moveit: str, out_dir: str) -> tuple[str, dict[str, str]]:
    """Return (urdf_text, {dst_rel: src_abs}) without writing anything."""
    xacro = os.path.join(moveit, XACRO_REL)
    meshes = os.path.join(moveit, MESH_REL)
    if not os.path.isfile(xacro):
        sys.exit(f"error: source xacro not found: {xacro}")

    tree = ET.parse(xacro)
    root = tree.getroot()
    # Drop the xacro namespace declaration; ET keeps it as an attribute-less
    # nsmap, so rebuild the root element cleanly.
    if root.tag != "robot":
        sys.exit(f"error: expected <robot> root, got <{root.tag}>")

    copies: dict[str, str] = {}

    def rewrite(el: ET.Element) -> None:
        fn = el.get("filename")
        if fn is None:
            return
        if fn.startswith(PKG_VISUAL):
            name = fn[len(PKG_VISUAL):]
            src = os.path.join(meshes, "genesis_wuji", name)
            el.set("filename", f"../meshes/visual/{name}")
            copies[f"meshes/visual/{name}"] = src
            if name.lower().endswith(".obj") and os.path.isfile(src):
                mtl = mtl_of(src)
                # Three column OBJs name an MTL the delivery never shipped
                # (lifting_Columns_*_visual.mtl); the mesh loads grey without it.
                if mtl and os.path.isfile(os.path.join(meshes, "genesis_wuji", mtl)):
                    copies[f"meshes/visual/{mtl}"] = os.path.join(meshes, "genesis_wuji", mtl)
                elif mtl:
                    print(f"note: {name} names missing material {mtl}; skipped", file=sys.stderr)
        elif fn.startswith(PKG_HULL):
            name = fn[len(PKG_HULL):]
            el.set("filename", f"../meshes/collision/{name}")
            copies[f"meshes/collision/{name}"] = os.path.join(meshes, "genesis_wuji_collision_hull", name)
        else:
            sys.exit(f"error: unexpected mesh reference {fn!r}")

    for mesh in root.iter("mesh"):
        rewrite(mesh)

    frozen = []
    for joint in root.findall("joint"):
        if joint.get("name") in COLUMN_JOINTS:
            if joint.get("type") != "prismatic":
                sys.exit(f"error: {joint.get('name')} is {joint.get('type')}, expected prismatic")
            joint.set("type", "fixed")
            for tag in ("axis", "limit", "dynamics", "safety_controller", "calibration", "mimic"):
                for child in joint.findall(tag):
                    joint.remove(child)
            frozen.append(joint.get("name"))
    if sorted(frozen) != sorted(COLUMN_JOINTS):
        sys.exit(f"error: expected to freeze {COLUMN_JOINTS}, froze {frozen}")

    missing = [s for s in copies.values() if not os.path.isfile(s)]
    if missing:
        sys.exit("error: referenced meshes missing in adam-moveit:\n  " + "\n  ".join(missing))

    n_links = len(root.findall("link"))
    n_joints = len(root.findall("joint"))
    n_fixed = sum(1 for j in root.findall("joint") if j.get("type") == "fixed")

    new_root = ET.Element("robot", {"name": "adam_u_wuji"})
    new_root.extend(list(root))
    ET.indent(new_root, space="  ")
    body = ET.tostring(new_root, encoding="unicode")

    header = f"""<?xml version="1.0"?>
<!-- GENERATED by tools/make_wuji_urdf.py. Do not edit.

     Adam-U (PNDbotics) with Wuji Hand 2 (Beta 2), the Genesis_SIM_test_003
     design. Vendored from adam-moveit:
       {XACRO_REL}
       adam-moveit commit {git_head(moveit)}
       source sha256 {sha256(xacro)}
       generated {dt.date.today().isoformat()}

     Differences from the source, all mechanical (see the script):
       - mesh URIs are relative to this file (../meshes/visual, ../meshes/collision)
       - {COLUMN_JOINTS[0]} and {COLUMN_JOINTS[1]} are FIXED
         (q=0, column fully extended); nothing drives the column
       - root element is a plain <robot>, not a xacro fragment

     {n_links} links, {n_joints} joints ({n_joints - n_fixed} revolute, {n_fixed} fixed).
     Root link: lifting_Columns_base. Hands: 20 independent revolute joints
     each, no coupling (per Wuji's own description). Flexion is positive.
-->
"""
    return header + body + "\n", copies


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--moveit", default=DEFAULT_MOVEIT, help="adam-moveit checkout")
    ap.add_argument("--out", default=OUT_DIR, help="output asset directory")
    ap.add_argument("--check", action="store_true", help="verify outputs match instead of writing")
    args = ap.parse_args()

    text, copies = build(args.moveit, args.out)
    urdf_path = os.path.join(args.out, "urdf", "adam_u_wuji.urdf")

    if args.check:
        bad = []
        if not os.path.isfile(urdf_path):
            bad.append(urdf_path)
        else:
            # Ignore the date/commit header when comparing.
            strip = lambda s: re.sub(r"<!--.*?-->", "", s, count=1, flags=re.S)  # noqa: E731
            if strip(open(urdf_path).read()) != strip(text):
                bad.append(urdf_path)
        for rel, src in copies.items():
            dst = os.path.join(args.out, rel)
            if not os.path.isfile(dst) or sha256(dst) != sha256(src):
                bad.append(dst)
        if bad:
            print("STALE:\n  " + "\n  ".join(bad))
            return 1
        print(f"OK: {urdf_path} and {len(copies)} meshes are current")
        return 0

    os.makedirs(os.path.dirname(urdf_path), exist_ok=True)
    for rel, src in copies.items():
        dst = os.path.join(args.out, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
    with open(urdf_path, "w") as f:
        f.write(text)
    n_obj = sum(1 for r in copies if r.endswith(".obj"))
    n_mtl = sum(1 for r in copies if r.endswith(".mtl"))
    n_stl = sum(1 for r in copies if r.lower().endswith(".stl"))
    print(f"wrote {urdf_path}")
    print(f"copied {n_obj} OBJ + {n_mtl} MTL visuals, {n_stl} STL collision hulls")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
