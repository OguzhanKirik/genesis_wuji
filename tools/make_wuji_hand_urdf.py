#!/usr/bin/env python3
"""Cut the right Wuji hand out of the vendored Adam-U URDF as its own robot.

For the finger-only experiment (Experiment 2) the arm is noise: the wrist is
fixed during the grasp and moves 10 cm straight up afterwards. So the hand
becomes a standalone fixed-base articulation:

    world  --wrist_lift (prismatic, z, 0..0.20 m)-->  r_wrist  -->  20 finger joints ...

`wrist_lift` is how the scripted lift moves the hand: a stiff position drive
on one joint, no IK, no arm sag. The world link is the fixed root; the hand's
pose over the table is the articulation's init_state in the env cfg.

Everything below r_wrist is copied verbatim from assets/robots/adam_u_wuji/
urdf/adam_u_wuji.urdf (itself vendored from adam-moveit), and the meshes are
referenced in place, so there is one copy of the hand geometry.

    python3 tools/make_wuji_hand_urdf.py --fingers 3   # -> urdf/wuji_hand_right_f3.urdf
    python3 tools/make_wuji_hand_urdf.py --fingers 2 --check
"""

from __future__ import annotations

import argparse
import copy
import datetime as dt
import os
import re
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "..", "assets", "robots")
SRC = os.path.join(ASSETS, "adam_u_wuji", "urdf", "adam_u_wuji.urdf")
def out_path(fingers: int) -> str:
    """One asset per finger count: each solved pose has its own lift axis, which
    is baked into the URDF, so the modes cannot share a file."""
    return os.path.join(ASSETS, "wuji_hand_right", "urdf", f"wuji_hand_right_f{fingers}.urdf")
ROOT_LINK = "r_wrist"
LIFT_RANGE = 0.20
# The prismatic lift axis, expressed in the HAND's own frame. The env spawns
# this articulation rotated into its pre-grasp orientation, and a joint axis
# rotates with its parent, so a naive (0, 0, 1) lift travels wherever the
# rotation points it -- measured: the wrist went sideways and dragged the bolt
# 7 cm across the table instead of lifting it. Setting the axis to the pose's
# "world up expressed in the hand frame" (the vector tools/find_pinch_pose.py
# prints as LIFT_AXIS) makes the joint travel exactly world-vertical once the
# hand is rotated. Keep this in step with HAND_ROT in the env config.
# One per finger count, matching POSE in genesis_rl/envs/wuji_synergy_grasp_env_cfg.py.
LIFT_AXIS_BY_FINGERS = {
    2: (0.158346, -0.987375, 0.004167),
    3: (0.510345, -0.849959, -0.130833),
}
LIFT_AXIS_BY_FINGERS[4] = LIFT_AXIS_BY_FINGERS[3]
DEFAULT_LIFT_AXIS = LIFT_AXIS_BY_FINGERS[3]


def build(src: str, lift_axis=DEFAULT_LIFT_AXIS) -> str:
    root = ET.parse(src).getroot()
    links = {l.get("name"): l for l in root.findall("link")}
    joints = root.findall("joint")
    by_parent: dict[str, list] = {}
    for j in joints:
        by_parent.setdefault(j.find("parent").get("link"), []).append(j)

    keep_links, keep_joints, stack = [], [], [ROOT_LINK]
    while stack:
        name = stack.pop()
        keep_links.append(name)
        for j in by_parent.get(name, []):
            keep_joints.append(j)
            stack.append(j.find("child").get("link"))

    out = ET.Element("robot", {"name": "wuji_hand_right"})
    for m in root.findall("material"):
        out.append(copy.deepcopy(m))
    world = ET.SubElement(out, "link", {"name": "world"})
    inertial = ET.SubElement(world, "inertial")
    ET.SubElement(inertial, "origin", {"xyz": "0 0 0", "rpy": "0 0 0"})
    ET.SubElement(inertial, "mass", {"value": "1.0"})
    ET.SubElement(inertial, "inertia", {"ixx": "0.001", "ixy": "0", "ixz": "0", "iyy": "0.001", "iyz": "0", "izz": "0.001"})
    lift = ET.SubElement(out, "joint", {"name": "wrist_lift", "type": "prismatic"})
    ET.SubElement(lift, "parent", {"link": "world"})
    ET.SubElement(lift, "child", {"link": ROOT_LINK})
    ET.SubElement(lift, "origin", {"xyz": "0 0 0", "rpy": "0 0 0"})
    ET.SubElement(lift, "axis", {"xyz": " ".join(f"{v:.6f}" for v in lift_axis)})
    ET.SubElement(lift, "limit", {"lower": "0", "upper": f"{LIFT_RANGE}", "effort": "200", "velocity": "0.5"})
    for name in keep_links:
        el = copy.deepcopy(links[name])
        for mesh in el.iter("mesh"):
            fn = mesh.get("filename")
            # ../meshes/visual/X.obj  ->  ../../adam_u_wuji/meshes/visual/X.obj
            mesh.set("filename", re.sub(r"^\.\./meshes/", "../../adam_u_wuji/meshes/", fn))
        out.append(el)
    for j in keep_joints:
        out.append(copy.deepcopy(j))

    n_rev = sum(1 for j in keep_joints if j.get("type") == "revolute")
    n_fix = sum(1 for j in keep_joints if j.get("type") == "fixed")
    ET.indent(out, space="  ")
    header = f"""<?xml version="1.0"?>
<!-- GENERATED by tools/make_wuji_hand_urdf.py from {os.path.relpath(src, os.path.join(HERE, '..'))}.
     Do not edit. Right Wuji Hand 2 as a standalone fixed-base robot:
       world -(wrist_lift, prismatic along {tuple(round(v, 4) for v in lift_axis)}, 0..{LIFT_RANGE} m)-> {ROOT_LINK}
       -> {n_rev} revolute finger joints
       ({n_fix} fixed tip/sensor links merge into the distal links at import).
     Meshes reference ../../adam_u_wuji/meshes/ so the hand geometry has one copy.
     generated {dt.date.today().isoformat()}
-->
"""
    return header + ET.tostring(out, encoding="unicode") + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", default=SRC)
    ap.add_argument("--out", default=None)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--fingers", type=int, choices=(2, 3, 4), default=3,
                    help="pick the lift axis for that finger count's solved pose")
    ap.add_argument("--lift-axis", type=float, nargs=3, default=None,
                    help="override the prismatic lift axis in the hand frame; see the note above")
    args = ap.parse_args()
    axis = tuple(args.lift_axis) if args.lift_axis else LIFT_AXIS_BY_FINGERS[args.fingers]
    if args.out is None:
        args.out = out_path(args.fingers)
    text = build(args.src, axis)
    strip = lambda s: re.sub(r"<!--.*?-->", "", s, count=1, flags=re.S)  # noqa: E731
    if args.check:
        ok = os.path.isfile(args.out) and strip(open(args.out).read()) == strip(text)
        print("OK" if ok else "STALE"); return 0 if ok else 1
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    open(args.out, "w").write(text)
    r = ET.fromstring(text)
    print(f"wrote {args.out}: {len(r.findall('link'))} links, {len(r.findall('joint'))} joints")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
